type LocaleContextValue = {
  locale: Locale;
  setLocale: (locale: Locale) => void;
  t: (value: string) => string;
};

const LocaleContext = createContext<LocaleContextValue | null>(null);

export function LocaleProvider({ children }: { children: ReactNode }) {
  const [locale, setLocale] = useState<Locale>(() => {
    try {
      return (
        (localStorage.getItem("nanajobs-locale") as Locale) ||
        (localStorage.getItem("kindred-locale") as Locale) ||
        "en"
      );
    } catch {
      return "en";
    }
  });

  const updateLocale = (next: Locale) => {
    setLocale(next);
    try {
      localStorage.setItem("nanajobs-locale", next);
      localStorage.setItem("kindred-locale", next);
    } catch {
      // ignore
    }
  };

  useEffect(() => {
    document.documentElement.lang = locale;
    if (locale === "am") {
      document.documentElement.classList.add("lang-am");
    } else {
      document.documentElement.classList.remove("lang-am");
    }
  }, [locale]);

  const value = useMemo(
    () => ({
      locale,
      setLocale: updateLocale,
      t: (value: string): string => {
        if (locale !== "am" || !value || typeof value !== "string") return value;
        const trimmed = value.trim();

        // Exact match
        if (translations[value]) return translations[value];
        if (translations[trimmed]) return translations[trimmed];

        // Case-insensitive match
        const lower = trimmed.toLowerCase();
        const foundKey = Object.keys(translations).find(
          (k) => k.toLowerCase() === lower
        );
        if (foundKey) return translations[foundKey];

        // Dynamic greeting: "Welcome back, {name}"
        if (trimmed.startsWith("Welcome back,") || trimmed.startsWith("Welcome back")) {
          const rest = trimmed.replace(/^Welcome back,?\s*/i, "");
          return rest ? `እንኳን ደህና መጡ፣ ${rest}` : "እንኳን ደህና መጡ";
        }

        // Dynamic count patterns: "{count} roles found", "{count} Candidate Applications"
        const countMatch = trimmed.match(/^(\d+)\s+(.+)$/);
        if (countMatch) {
          const num = countMatch[1];
          const rest = countMatch[2].trim();
          const translatedRest =
            translations[rest] ||
            translations[Object.keys(translations).find((k) => k.toLowerCase() === rest.toLowerCase()) || ""];
          if (translatedRest) return `${num} ${translatedRest}`;
        }

        return value;
      },
    }),
    [locale]
  );

  return <LocaleContext.Provider value={value}>{children}</LocaleContext.Provider>;
}

export function useLocale() {
  const context = useContext(LocaleContext);
  if (!context) {
    throw new Error("useLocale must be used within LocaleProvider");
  }
  return context;
}
